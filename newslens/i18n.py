def _chinese(language):
    return language in {"zh", "zh-CN", "中文"}


def translate(text, language="en", **values):
    """Translate known interface strings, leaving unknown/source content intact."""
    result = EN_TO_ZH.get(text, text) if _chinese(language) else text
    if _chinese(language) and result == text:
        match = re.fullmatch(r"API returned HTTP (\d{3})", text)
        if match:
            result = "接口返回 HTTP " + match[1]
    return result.format(**values) if values else result


