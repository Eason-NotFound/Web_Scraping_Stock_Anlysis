def localize_log(message, language="en"):
    """Localize saved structured messages for display without rewriting any record."""
    for pattern, english, chinese in _LOG_PATTERNS:
        match = re.fullmatch(pattern, message)
        if match:
            values = list(match.groups())
            if english.startswith("Analysis saved") and _chinese(language):
                values[-1] = translate(values[-1], language)
            return (chinese if _chinese(language) else english).format(*values)
    if _chinese(language):
        # The evidence group is copied byte-for-byte; only our wrapper is localized.
        match = re.fullmatch(r"New related news \((.*?)\); (positive|negative|neutral|unclear) sentiment\. Evidence: (.*)", message, re.DOTALL)
